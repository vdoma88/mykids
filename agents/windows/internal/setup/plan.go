package setup

import "fmt"

// Порядок шагов — не формальность, а решение.
//
// Привязка идёт до регистрации службы. Наоборот было бы естественнее (сначала
// поставить, потом настроить), но неверный токен оставил бы на машине
// зарегистрированную службу, которая работает автономно и ничего родителю не
// шлёт. Выглядит это как «установилось», а на деле нет, и обнаружится через
// день. Лучше упасть на привязке, не тронув службу.
//
// Проверка учётной записи ребёнка — первым делом, до копирования файлов:
// ребёнок-администратор остановит службу из оснастки, и всё остальное
// бессмысленно. Останавливаться на этом после того, как половина уже
// разложена по дискам, значит оставить за собой мусор.

// Step — шаг установки.
type Step struct {
	Name string
	// Why — зачем он. Идёт в отчёт, который родитель пересылает, когда что-то
	// не вышло: шаг без объяснения ни о чём не говорит тому, кто помогает.
	Why string
}

// Steps — что и в каком порядке делает установщик.
func Steps() []Step {
	return []Step{
		{"Права администратора",
			"служба регистрируется на всю машину, а такое делает только администратор"},
		{"Учётная запись ребёнка",
			"агент в учётной записи администратора не защищает ни от чего: ребёнок просто остановит службу"},
		{"Копирование агента",
			"агент должен лежать там, где ребёнок его не сотрёт"},
		{"Каталог данных",
			"в нём состояние учёта и очередь расхода; ребёнку туда доступа быть не должно"},
		{"Привязка устройства",
			"без неё агент работает автономно и ничего родителю не шлёт"},
		{"Регистрация службы",
			"служба считает время и принимает решения"},
		{"Запуск службы",
			"пока она остановлена, время не считается"},
	}
}

// Explain превращает неудачу шага в то, что родителю делать дальше.
//
// Текст ошибки от Windows сам по себе бесполезен: «отказано в доступе» не
// говорит, в чём именно. Поэтому к каждой неудаче прибавляется следующий шаг,
// а не только диагноз.
func Explain(step string, err error) string {
	var next string
	switch step {
	case "Права администратора":
		next = "Закройте это окно и запустите программу правой кнопкой → «Запуск от имени администратора»."
	case "Учётная запись ребёнка":
		next = "Выведите учётную запись ребёнка из группы «Администраторы» и повторите."
	case "Копирование агента":
		next = "Проверьте, что mykids-agent.exe лежит рядом с этой программой и не занят запущенной службой."
	case "Каталог данных":
		next = "Каталог занят или права на него уже кем-то изменены. Закройте программы, которые могут его держать."
	case "Привязка устройства":
		next = "Проверьте адрес сервера и токен. Токен показывается один раз: если он потерян, выдайте новый на странице ребёнка."
	case "Регистрация службы":
		next = "Возможно, служба уже установлена. Удалите её и повторите: mykids-agent.exe service uninstall"
	case "Запуск службы":
		next = "Служба зарегистрирована, но не запустилась. Загляните в журнал событий Windows."
	default:
		next = "Пришлите этот отчёт тому, кто настраивает."
	}
	return fmt.Sprintf("%s: %v\n    что делать: %s", step, err, next)
}

// Done — что проверить, когда всё прошло.
//
// Установка, которая кончается словом «готово», оставляет родителя гадать,
// готово ли. Поэтому кончается она списком того, что можно увидеть глазами.
func Done(in Input) []string {
	return []string{
		"Готово. Что проверить прямо сейчас:",
		"  1. Войдите в учётную запись ребёнка и запустите mykids-check.exe — он скажет, что видит агент.",
		"  2. В трее у ребёнка должен появиться значок с остатком времени.",
		"  3. Откройте " + in.ChildURL + " — там задания и магазин.",
		"",
		"Удаление: mykids-agent.exe service stop, затем service uninstall.",
	}
}
