#!/usr/bin/env bash
# Проверка разделения службы и помощника на двух настоящих процессах.
#
#   agents/windows/two-process-test.sh
#
# Юнит-тесты проверяют протокол и учёт по отдельности. Здесь проверяется то,
# что видно только на живом запуске: что службу запускают одну, а помощника она
# поднимает сама; что время списывается с той скоростью, с какой идёт; что
# предупреждение приходит раньше блокировки; что ребёнку объяснили причину; и
# что снятие помощника не останавливает счёт, а самого помощника возвращает.
#
# Именно так нашлась потеря времени на округлении: помощник шлёт наблюдения
# каждую секунду, таймер службы тикает своим чередом, промежутки выходят по
# полсекунды — и час экрана превращался в считанные минуты.
set -euo pipefail

cd "$(dirname "$0")"
BIN=$(mktemp -d)/mykids-agent
DATA=$(mktemp -d)
SOCK="$DATA/agent.sock"
LIMIT_MINUTES=${LIMIT_MINUTES:-2}
LIMIT_SECONDS=$(( LIMIT_MINUTES * 60 ))

go build -o "$BIN" ./cmd/mykids-agent

# Две минуты в день с предупреждением за минуту: лимит кончится за время
# прогона, и первую минуту предупреждения быть не должно. Иначе проверка
# «предупредили заранее» прошла бы и для надписи, висящей всегда.
cat > "$DATA/policy.json" <<EOF
{"timezone":"UTC","dailyLimitMinutes":[$LIMIT_MINUTES,$LIMIT_MINUTES,$LIMIT_MINUTES,$LIMIT_MINUTES,$LIMIT_MINUTES,$LIMIT_MINUTES,$LIMIT_MINUTES],
 "carryOverMaxMinutes":0,
 "windows":[],"alwaysAllowed":["explorer.exe"],"idleThresholdSeconds":120,"warnBeforeMinutes":1}
EOF

pids=()
cleanup() {
  for p in "${pids[@]:-}"; do kill "$p" 2>/dev/null || true; done
  wait 2>/dev/null || true
}
trap cleanup EXIT

# Имя активного окна задаётся службе, а не помощнику: помощника запускает
# служба, и окружение он наследует от неё — ровно как в бою наследует
# окружение ребёнка.
MYKIDS_FAKE_PROCESS=game.exe \
  "$BIN" -data "$DATA" -pipe "$SOCK" -interval 1s serve > "$DATA/serve.log" 2>&1 &
pids+=($!)

for _ in $(seq 1 50); do [ -S "$SOCK" ] && break; sleep 0.2; done
if [ ! -S "$SOCK" ]; then
  echo "служба не открыла канал:" >&2; cat "$DATA/serve.log" >&2; exit 1
fi

# Помощника запускает служба, а не мы: ровно это и происходит в бою, и ровно
# этого раньше не было — установка получалась слепой.
helper_of() { pgrep -f "^$BIN .*-pipe $SOCK .*helper$" | head -1; }

for _ in $(seq 1 50); do [ -n "$(helper_of)" ] && break; sleep 0.2; done
helper_pid=$(helper_of)
if [ -z "$helper_pid" ]; then
  echo "служба не подняла помощника:" >&2; cat "$DATA/serve.log" >&2; exit 1
fi
echo "служба поднялась и сама запустила помощника (pid $helper_pid)"

# Помощник работает с правами ребёнка, а каталог данных от ребёнка закрыт
# нарочно: там состояние учёта и очередь расхода. Помощнику он не нужен —
# всё приходит по каналу. Если он всё-таки туда полезет, то в бою упадёт на
# правах, служба будет поднимать его снова и снова, и через пять раз обвинит
# ребёнка в снятии наблюдателя, которого он не трогал.
#
# Канал у этой пробы свой и заведомо мёртвый, а не общий с настоящей парой.
# Иначе проба на две секунды становилась бы вторым помощником у той же службы:
# слала бы свои наблюдения вперемешку с настоящими и портила ровно тот счёт,
# который этот тест и проверяет. Мёртвый канал тут ничего не ослабляет —
# помощник обязан пережить и отсутствие службы (он её переспрашивает), и
# закрытый каталог; проверяем второе, первое ему просто не мешает.
"$BIN" -data /proc/нет-доступа -pipe "$DATA/нет-службы.sock" -interval 1s helper \
  > "$DATA/closed.log" 2>&1 &
closed_pid=$!
pids+=("$closed_pid")
sleep 2
if ! kill -0 "$closed_pid" 2>/dev/null; then
  echo "помощник не пережил недоступного каталога данных:" >&2
  cat "$DATA/closed.log" >&2
  echo "он работает с правами ребёнка, и каталог службы ему недоступен" >&2
  exit 1
fi
kill "$closed_pid" 2>/dev/null || true
echo "помощник не трогает каталог данных службы"

# Ждём, пока лимит кончится и помощник закроет экран. С запасом вдвое: если
# время списывается медленнее, чем идёт, мы это и хотим поймать.
deadline=$(( $(date +%s) + LIMIT_SECONDS * 2 + 15 ))
until grep -q "ЭКРАН ЗАКРЫТ" "$DATA/serve.log" 2>/dev/null; do
  if [ "$(date +%s)" -gt "$deadline" ]; then
    echo "за ${LIMIT_SECONDS}-секундный лимит экран так и не закрылся —" >&2
    echo "время списывается медленнее, чем идёт" >&2
    tail -20 "$DATA/serve.log" "$DATA/serve.log" >&2
    exit 1
  fi
  sleep 1
done
echo "лимит исчерпан, помощник закрыл экран"

# Дальше — про то, что видит подросток. Проверять это на живом запуске нужно
# по той же причине, что и учёт: порядок событий во времени юнит-тестом не
# ловится, а именно он тут и важен.
line_of() { grep -n "$1" "$DATA/serve.log" | head -1 | cut -d: -f1; }
warned=$(line_of "ПРЕДУПРЕЖДЕНИЕ" || true)
blocked=$(line_of "ЭКРАН ЗАКРЫТ")

if [ -z "$warned" ]; then
  echo "экран закрылся без предупреждения:" >&2; cat "$DATA/serve.log" >&2
  echo "потерять экран посреди игры без предупреждения — худшее, что можно сделать" >&2
  exit 1
fi
if [ "$warned" -ge "$blocked" ]; then
  echo "предупреждение появилось не раньше блокировки:" >&2
  cat "$DATA/serve.log" >&2; exit 1
fi
echo "предупреждение пришло раньше блокировки (строки $warned и $blocked)"

if grep "ПРЕДУПРЕЖДЕНИЕ" "$DATA/serve.log" | grep -q "0 минут"; then
  echo "в предупреждении осталось «0 минут»:" >&2
  grep "ПРЕДУПРЕЖДЕНИЕ" "$DATA/serve.log" >&2
  echo "ноль — не предупреждение, а недоразумение: время ещё идёт" >&2
  exit 1
fi

# Закрытый экран без объяснения читается как наказание, а не как правило.
for expect in "кончилось" "Завтра будет"; do
  if ! grep -q "$expect" "$DATA/serve.log"; then
    echo "на закрытом экране нет «$expect»:" >&2; cat "$DATA/serve.log" >&2; exit 1
  fi
done
echo "на закрытом экране сказано, почему и что будет завтра"

# Снимаем помощника: служба обязана продолжать считать, а не считать это
# отдыхом, и обязана поднять его обратно.
kill -9 "$helper_pid" 2>/dev/null || true
before=$(python3 -c "import json;print(json.load(open('$DATA/state.json'))['today']['usedSeconds'])")
sleep 40  # дольше порога молчания и дольше периода сохранения
after=$(python3 -c "import json;print(json.load(open('$DATA/state.json'))['today']['usedSeconds'])")

if [ "$after" -le "$before" ]; then
  echo "после снятия помощника счёт остановился: было $before, стало $after" >&2
  echo "снять наблюдателя не должно быть способом получить бесплатное время" >&2
  exit 1
fi
echo "помощник снят, служба продолжает считать: $before -> $after"

revived=$(helper_of)
if [ -z "$revived" ] || [ "$revived" = "$helper_pid" ]; then
  echo "служба не подняла помощника обратно (было $helper_pid, стало «$revived»):" >&2
  tail -20 "$DATA/serve.log" >&2
  echo "без помощника служба слепа: окон не видит, оверлей рисовать некому" >&2
  exit 1
fi

# Один, а не стопка: проверка «жив ли помощник», которая всегда отвечает «нет»,
# выглядит работающей ровно до того момента, когда помощники начнут копиться.
alive=$(pgrep -cf "^$BIN .*-pipe $SOCK .*helper$")
if [ "$alive" != 1 ]; then
  echo "помощников запущено $alive вместо одного" >&2
  exit 1
fi
echo "помощник поднят обратно службой (pid $revived), и он один"
# Встречная проверка экрана: служба спрашивает Windows сама и верит ей, а не
# помощнику. Вне Windows обе стороны отвечают из переменных окружения — тем же
# способом, что и активное окно, и ровно затем же: разойтись в показаниях два
# настоящих процесса должны по-настоящему.
#
# Проверяем самую выгодную ложь: помощник заявляет заблокированный экран и не
# меняет окно. Противоречия нет, старой проверке ловить его не на чем — и без
# второго источника время не списывалось бы вообще.
#
# Оба прогона обязательны. Один, без контрольного, прошёл бы и в том случае,
# если бы ложь помощника просто не работала: тогда время списывалось бы всегда
# и доказывало бы это не встречную проверку, а ничего.
# LOCK_WATCH — сколько наблюдать. Дольше периода сохранения состояния (30 с),
# иначе state.json ещё не существует и читать нечего. Молчаливое «ну пусть
# будет ноль» тут недопустимо: ноль — это и есть ожидаемый ответ в одном из
# прогонов, и отсутствующий файл выглядел бы как доказательство.
LOCK_WATCH=35

lock_run() {
  local dir own used
  dir=$(mktemp -d)
  own=$1
  cp "$DATA/policy.json" "$dir/policy.json"

  MYKIDS_FAKE_PROCESS=game.exe MYKIDS_FAKE_HELPER_LOCK=1 MYKIDS_FAKE_LOCK="$own" \
    "$BIN" -data "$dir" -pipe "$dir/lock.sock" -interval 1s serve \
    > "$dir/serve.log" 2>&1 &
  pids+=($!)

  for _ in $(seq 1 50); do [ -S "$dir/lock.sock" ] && break; sleep 0.2; done
  if [ ! -S "$dir/lock.sock" ]; then
    echo "служба не открыла канал:" >&2; cat "$dir/serve.log" >&2; exit 1
  fi

  sleep "$LOCK_WATCH"
  if [ ! -f "$dir/state.json" ]; then
    echo "за $LOCK_WATCH с состояние так и не сохранилось — читать нечего:" >&2
    cat "$dir/serve.log" >&2
    exit 1
  fi
  used=$(python3 -c "import json;print(json.load(open('$dir/state.json'))['today']['usedSeconds'])")
  echo "$used"
}

# Контрольный: своего источника нет, и служба верит помощнику на слово. Это
# ровно та дыра, ради которой всё и делалось, — она обязана быть видна.
blind=$(lock_run "")
if [ "$blind" -gt 5 ]; then
  echo "без своего источника служба насчитала $blind секунд, хотя помощник заявил" >&2
  echo "заблокированный экран: значит, проба меряет не то, что думает" >&2
  exit 1
fi
echo "контрольный: веря помощнику на слово, служба насчитала $blind с — дыра на месте"

# Основной: служба спросила Windows и получила «открыт».
seeing=$(lock_run "off")
if [ "$seeing" -lt $(( LOCK_WATCH / 2 )) ]; then
  echo "со своим источником за $LOCK_WATCH с насчитано всего $seeing секунд" >&2
  echo "ложь помощника о блокировке всё ещё даёт бесплатное время" >&2
  exit 1
fi
echo "встречная проверка: спросив Windows, служба насчитала $seeing с вместо $blind"

echo "разделение службы и помощника: все проверки пройдены"
