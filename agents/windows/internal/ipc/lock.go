package ipc

// Состояние экрана — единственное, что служба может узнать о рабочем столе
// сама, не спрашивая помощника.
//
// Всё остальное — активное окно, время простоя — видно только из сессии
// пользователя, а служба живёт в нулевой. Но состояние сессии Windows хранит
// у себя, и на этот ответ помощник повлиять не может никак.
//
// Это важно по двум причинам, и вторая — не про обман.
//
// Первая: заявить «экран заблокирован» и замереть на одном окне — самая
// выгодная ложь из возможных. Проверка на противоречии (без ввода окна не
// переключаются) её не ловит: противоречия нет, а время не списывается
// никогда.
//
// Вторая, и в обычной жизни более частая: пока помощник молчит, служба
// считает, что экраном пользуются, — иначе снять наблюдателя означало бы
// получить бесплатное время. Но помощник перезапускается и сам по себе, и
// ребёнок, который заблокировал экран и ушёл, платил за эти полминуты ни за
// что. Свой источник снимает этот вопрос: не надо гадать, если можно спросить.

// LockState — что служба узнала о блокировке экрана сама.
type LockState int

const (
	// LockUnknown — спросить не удалось: не Windows, сессии нет, вызов не
	// прошёл. Тогда всё решает помощник, как и раньше.
	LockUnknown LockState = iota
	// LockOff — экран открыт.
	LockOff
	// LockOn — экран заблокирован.
	LockOn
)

func (l LockState) String() string {
	switch l {
	case LockOff:
		return "открыт"
	case LockOn:
		return "заблокирован"
	default:
		return "неизвестно"
	}
}

// LockSource — источник состояния экрана, не зависящий от помощника.
type LockSource interface {
	// SessionLock — состояние экрана в сессии ребёнка глазами службы.
	SessionLock() LockState
}

// LockFunc — функция как источник, чтобы не заводить тип ради одного метода.
type LockFunc func() LockState

func (f LockFunc) SessionLock() LockState { return f() }
