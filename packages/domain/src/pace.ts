/**
 * Антифарм: кредиты за решённое, а не за угаданное.
 *
 * Пакет из десяти заданий с четырьмя вариантами ответа можно прокликать
 * наугад за полминуты. Четверть попаданий — чистая случайность, и кредиты за
 * них начисляются наравне с настоящими. Пока это так, вся экономика держится
 * на честном слове ребёнка, а смысл системы в том, чтобы время зарабатывалось
 * учёбой.
 *
 * Длительности у попытки нет, и добавить её нельзя: измерял бы её браузер
 * ребёнка, а он на его стороне. Подменённая страница сообщила бы любое число —
 * ровно та же беда, что с помощником на Windows, и решение то же: смотреть не
 * на то, что говорят, а на то, что видно самому.
 *
 * Сервер штампует время прихода каждой попытки сам. Промежутки между ними
 * подделать нельзя, не замедлившись на самом деле, — а замедлиться и значит
 * перестать угадывать.
 *
 * Чего эта проверка сознательно не делает:
 *
 *  - не наказывает за одну быструю попытку. Ребёнок, который знает ответ,
 *    отвечает быстро — это и есть цель, а не нарушение;
 *  - не отнимает уже начисленное. Задним числом забирать кредиты значило бы
 *    учить, что правила меняются;
 *  - не обвиняет. Формулировка называет правило, а не ставит диагноз: если
 *    проверка ошиблась, подросток прочтёт обвинение, которого не заслужил, и
 *    это дороже, чем пропущенная попытка.
 */

/** Настройки темпа. Лежат рядом с экономикой: это её часть, а не защита от взлома. */
export interface PaceConfig {
  /**
   * Быстрее этого промежутка между попытками ответ неправдоподобен.
   *
   * Считаем от прихода предыдущей попытки: прочитать задание, подумать и
   * ответить быстрее нескольких секунд нельзя даже зная ответ — нужно хотя бы
   * прочитать.
   */
  minSecondsBetween: number;
  /**
   * Сколько неправдоподобно быстрых подряд считать угадыванием.
   *
   * Не одна: быстрая попытка бывает честной. Несколько подряд — уже способ
   * решения, а не совпадение.
   */
  streak: number;
}

export const defaultPaceConfig: PaceConfig = {
  minSecondsBetween: 4,
  streak: 3,
};

export interface PaceInput {
  /**
   * Время прихода предыдущих попыток этого ребёнка, новейшая первой.
   *
   * По часам сервера. Часам устройства здесь верить нельзя тем более, чем
   * в остальных местах: именно их и подкрутили бы.
   */
  previousAt: readonly Date[];
  now: Date;
  config?: PaceConfig;
}

export type PaceVerdict =
  | { tooFast: false; fastStreak: number }
  | { tooFast: true; fastStreak: number; message: string };

/**
 * Не слишком ли быстро идут ответы.
 *
 * Возвращает и длину серии, а не только решение: родителю в журнале полезно
 * видеть не «отклонено», а насколько быстро отвечали.
 */
export function checkPace(input: PaceInput): PaceVerdict {
  const config = input.config ?? defaultPaceConfig;
  const streak = fastStreak(input.previousAt, input.now, config.minSecondsBetween);

  if (streak < config.streak) {
    return { tooFast: false, fastStreak: streak };
  }
  return {
    tooFast: true,
    fastStreak: streak,
    message:
      'Кредиты начисляются за решённое, а не за угаданное: ' +
      `последние ${streak} ответа пришли быстрее чем за ${config.minSecondsBetween} с. ` +
      'Реши это задание не торопясь — оно зачтётся.',
  };
}

/**
 * Длина серии подряд идущих слишком коротких промежутков, считая от текущего
 * момента назад.
 *
 * Серия рвётся на первом же нормальном промежутке: ребёнок, который отвлёкся
 * и вернулся, начинает с чистого листа.
 */
function fastStreak(previousAt: readonly Date[], now: Date, minSeconds: number): number {
  let streak = 0;
  let at = now;
  for (const prev of previousAt) {
    const gap = (at.getTime() - prev.getTime()) / 1000;
    // Отрицательный промежуток означает, что порядок нарушен: попытки пришли
    // не по возрастанию времени. Считать это быстрым ответом нельзя — это
    // ошибка в данных, а не поведение ребёнка.
    if (gap < 0 || gap >= minSeconds) break;
    streak++;
    at = prev;
  }
  return streak;
}
