-- Возвращает белый список агента тем, у кого его стёрла ошибка.
--
-- До 0.8.0 админка при каждом сохранении правил присылала пустой
-- alwaysAllowed, и сервер записывал его как есть: первая же правка лимитов
-- выкидывала из «всегда разрешённого» Проводник и сам агент. Пустым список
-- мог стать только так — интерфейс его не редактировал, — поэтому пустой
-- список здесь означает «стёрт», а не «так задумано».
--
-- То, что родитель добавлял туда сам через API, вернуть нельзя: оно стёрто
-- вместе со всем остальным. Возвращаются только значения по умолчанию.
UPDATE "Policy"
SET "alwaysAllowed" = ARRAY['explorer.exe', 'mykids-agent.exe']
WHERE cardinality("alwaysAllowed") = 0;
