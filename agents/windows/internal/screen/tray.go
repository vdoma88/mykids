package screen

import (
	"fmt"
	"unicode/utf8"

	"github.com/vdoma88/mykids/agents/windows/internal/usage"
)

// Значок в трее — единственное, что видно, пока ничего не закрыто.
//
// До сих пор агент был невидим до самого конца: сначала ничего, потом полоса
// за несколько минут, потом закрытый экран. Для подростка это выглядит как
// слежка, которая вдруг вмешалась, — а договаривались о правиле. Правило,
// которое нельзя посмотреть, ничем не отличается от произвола.
//
// Поэтому в трее всегда видно, сколько осталось, и оттуда же открываются
// задания. Слова готовит служба, помощник только рисует: причина та же, что и
// у экрана, — подменённый помощник не должен иметь возможности написать
// ребёнку «всё в порядке, играй дальше».

// TipLimit — сколько символов Windows показывает в подписи под курсором.
//
// В NOTIFYICONDATA под неё отведено 128 знаков вместе с завершающим нулём.
// Длиннее — не обрезается, а отбрасывается целиком: подпись просто не
// появляется, и выглядит это как неработающий значок.
const TipLimit = 127

// Tray — значок в трее: подпись под курсором и меню по щелчку.
type Tray struct {
	Tip   string
	Items []Item
}

// Item — пункт меню.
type Item struct {
	Label string
	// URL — что открыть по щелчку. Пусто означает строку, которую можно
	// только прочитать: остаток времени, причина закрытия.
	URL string
	// Separator — разделительная черта. Остальные поля при этом пусты.
	Separator bool
}

// BuildTray собирает значок из того же решения, из которого строится экран.
//
// Пункта «Выход» здесь нет и не будет. Помощник — наблюдатель: дав ребёнку
// закрыть его одним щелчком, мы бы сами предложили способ получить бесплатное
// время. Снять его можно и так, через диспетчер задач, но это служба заметит
// и поднимет его обратно, а пункт в меню выглядел бы разрешением.
func BuildTray(v usage.Verdict, c Context) Tray {
	t := Tray{Tip: trayTip(v)}
	t.Items = append(t.Items, Item{Label: trayState(v)})

	if c.Credits > 0 {
		t.Items = append(t.Items, Item{Label: fmt.Sprintf("Кредитов: %d", c.Credits)})
	}

	if c.ChildURL != "" {
		t.Items = append(t.Items,
			Item{Separator: true},
			Item{Label: "Задания и магазин", URL: c.ChildURL},
		)
	}
	return t
}

// trayTip — подпись под курсором: имя программы и главное число.
//
// Имя нужно: в трее десяток значков, и без него непонятно, чей этот.
func trayTip(v usage.Verdict) string {
	return cut("MyKids · "+trayState(v), TipLimit)
}

// trayState — одна строка о том, что происходит сейчас.
//
// Числа, а не оценки, и то же самое, что скажет экран. Расхождение здесь
// дороже, чем кажется: подросток сверит подпись с надписью на закрытом экране
// первым же делом, и если они разойдутся, доверия не будет ни к одной.
func trayState(v usage.Verdict) string {
	switch {
	case !v.Allow && v.Window != "":
		return windowTitle(v)
	case !v.Allow:
		return "Время на сегодня кончилось"
	default:
		return fmt.Sprintf("Осталось %s", leftWord(v.LeftSecs))
	}
}

// cut укорачивает строку до n знаков по границе символа.
//
// По знакам, а не по байтам: в UTF-8 русская буква занимает два, и обрезка по
// байтам разрубила бы её пополам. Многоточие ставим только если что-то и
// правда отрезали.
func cut(s string, n int) string {
	if utf8.RuneCountInString(s) <= n {
		return s
	}
	runes := []rune(s)
	return string(runes[:n-1]) + "…"
}
