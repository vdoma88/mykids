//go:build windows

package win32

import (
	"golang.org/x/sys/windows"
)

// utf16 — строка для Windows, которую вызывающий обязан удержать живой.
//
// Go-указатель, превращённый в uintptr, для сборщика мусора указателем быть
// перестаёт. В вызове через LazyProc.Call правило «аргумент системного вызова
// продлевает жизнь» не действует: это обычная функция, а не syscall.Syscall.
// Буфер может быть собран прямо в тот момент, когда Windows его читает.
//
// Проявляется это не там, где ошибка: пока памяти вдоволь, всё работает.
// Именно так и нашлось — окно проверки переживало две строки отчёта и
// исчезало без единого слова на тридцати, когда сборщик успевал сработать.
//
// Поэтому везде ниже один и тот же порядок: получить срез, передать
// &срез[0] прямо в аргументе вызова, а сразу после вызова — runtime.KeepAlive.
func utf16(s string) []uint16 {
	b, err := windows.UTF16FromString(s)
	if err != nil {
		// Строка с нулевым байтом внутри: до Windows её всё равно не донести,
		// но и ронять программу из-за подписи на кнопке незачем.
		return []uint16{0}
	}
	return b
}
