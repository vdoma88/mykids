//go:build windows

package main

import (
	"os"
	"path/filepath"
)

// defaultDataDir — каталог агента на машине целиком, а не в профиле.
//
// Профиль тут не годится принципиально: служба работает под LocalSystem, а
// привязку делает родитель из своей учётной записи администратора. У них
// разные %APPDATA%, и привязка, сделанная родителем, службе просто не видна —
// она молча работала бы автономно, а родитель ждал бы данных в админке.
//
// %ProgramData% решает и вторую задачу: у ребёнка нет прав на изменение
// лежащих там файлов службы, так что ни состояние учёта, ни очередь расхода
// он не сотрёт. Права на каталог инсталлятор ужесточает дополнительно.
func defaultDataDir() string {
	if dir := os.Getenv("ProgramData"); dir != "" {
		return filepath.Join(dir, "MyKids")
	}
	// Переменной нет — система очень старая или очень сломанная; не выдумываем.
	if dir, err := os.UserConfigDir(); err == nil {
		return filepath.Join(dir, "MyKids")
	}
	return "."
}
