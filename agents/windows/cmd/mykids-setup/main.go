// mykids-setup — панель MyKids на компьютере ребёнка и помощник установщика.
//
// Двойной щелчок (или «Панель MyKids» в меню «Пуск») открывает окно: работает
// ли служба, отвечает ли сервер, чей это компьютер и сколько у ребёнка
// осталось; там же перепривязка и перезапуск службы. Раньше всё это
// узнавалось командой status в PowerShell — то есть не узнавалось вовсе.
//
// С командой (accounts, status, verify, stop, apply) программу вызывает мастер
// установки; см. cli.go.
package main

import (
	"fmt"
	"os"
)

// version подменяется при сборке релиза: build.sh передаёт её через -ldflags.
// По умолчанию — «dev», а не число. Число здесь пришлось бы править руками в
// трёх местах на каждый релиз, и оно неизбежно отставало бы: так и вышло —
// агент и проверка сообщали 0.5.0, когда установщик был уже 0.6.0. Сборка, не
// прошедшая через build.sh, врать о своей версии не должна.
var version = "dev"

func main() {
	// С командой программу запускает мастер установки; без команды — человек
	// двойным щелчком, и тогда это окно установки, как раньше.
	if isCommand(os.Args[1:]) {
		os.Exit(runCommand(os.Args[1:]))
	}
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "ошибка:", err)
		os.Exit(1)
	}
}
