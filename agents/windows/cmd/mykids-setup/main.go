// mykids-setup — установка агента без командной строки.
//
// До него установка выглядела так: открыть PowerShell от администратора,
// набрать команду с адресом сервера, токеном и именем учётной записи. Это
// умеет не всякий родитель, а те, кто умеет, ошибаются в токене, который
// показывается один раз. Программа, которую нельзя поставить, не работает —
// сколько бы всего внутри неё ни было правильно.
package main

import (
	"fmt"
	"os"
)

// version подменяется при сборке релиза: build.sh передаёт её через -ldflags.
// По умолчанию — «dev», а не число. Число здесь пришлось бы править руками в
// трёх местах на каждый релиз, и оно неизбежно отставало бы: так и вышло —
// агент и проверка сообщали 0.5.0, когда установщик был уже 0.6.0. Сборка, не
// прошедшая через build.sh, врать о своей версии не должна.
var version = "dev"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "ошибка:", err)
		os.Exit(1)
	}
}
